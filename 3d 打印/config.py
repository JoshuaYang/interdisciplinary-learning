import math

# ------------------------------------------------------------
# 1. 圆锥几何参数与数学函数
# ------------------------------------------------------------
# 原始双圆锥：X²/a² + Y²/b² - Z²/c² = 0。
# a、b、c 是方程系数，不是有限圆锥的高度或底面半径。
# 本课取上半锥 0 <= Z <= H，再翻转为尖顶朝上的打印摆放。
a = 2.0
b = 2.0
c = 2.0
H = 2.0                        # 单独设置截取高度，原始圆锥本身无限延伸
R = a * H / c                  # a = b 时，截取底圆半径

def function_y(x, z):
    """摆放后的圆锥：y = max(0, H - c * sqrt((x/a)^2 + (z/b)^2))。

    原始坐标 (X, Y, Z) 映射为内部坐标 (x, y, z) = (X, H-Z, -Y)。
    尖顶为 (0, H, 0)，底面位于 y = 0；引擎再转为打印 Z 轴向上。
    max 将底面边界外的高度截为 0，便于二分查找边界。
    """
    return max(0.0, H - c * math.sqrt((x / a)**2 + (z / b)**2))


